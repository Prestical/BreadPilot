// Copies every reviewed part pack (parts/<id>/) into src/parts.generated.ts, so the browser
// bundle, the API bundle and the tests all read the same data without file access at runtime.
// The output is gitignored and regenerated before tests, dev servers, type checks and builds:
// adding a part means adding one folder. Draft packs are left out (they need a human review).
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

export const PARTS_DIR = fileURLToPath(new URL("../../../parts/", import.meta.url));
export const PARTS_TS_PATH = fileURLToPath(new URL("../src/parts.generated.ts", import.meta.url));

export interface RawPack {
  dir: string;
  files: Record<string, unknown>;
  driver?: { file: string; source: string };
}

/** Every pack folder as it is on disk (top-level JSON files and the named driver). */
export function readPacks(dir = PARTS_DIR, opts: { drafts?: boolean } = {}): RawPack[] {
  const out: RawPack[] = [];
  for (const name of readdirSync(dir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()) {
    const folder = join(dir, name);
    const files: Record<string, unknown> = {};
    for (const f of readdirSync(folder).filter((f) => f.endsWith(".json")).sort()) {
      try {
        files[f] = JSON.parse(readFileSync(join(folder, f), "utf8"));
      } catch (err) {
        throw new Error(`parts/${name}/${f}: not valid JSON (${(err as Error).message})`);
      }
    }
    const meta = files["pack.json"] as { review?: { status?: string }; driver?: unknown } | undefined;
    if (meta?.review?.status === "draft" && !opts.drafts) {
      console.warn(`parts/${name}: draft pack left out (it needs a human review first)`);
      continue;
    }
    const pack: RawPack = { dir: name, files };
    if (typeof meta?.driver === "string" && existsSync(join(folder, meta.driver))) pack.driver = { file: meta.driver, source: readFileSync(join(folder, meta.driver), "utf8") };
    out.push(pack);
  }
  return out;
}

export function partsModule(packs = readPacks()): string {
  return [
    "// Generated by scripts/gen-parts.ts from parts/*/. Do not edit: run `npm run gen:parts` (it also runs",
    "// automatically before tests, dev servers, type checks and builds). Not committed.",
    'import type { PackSource } from "./packs";',
    "",
    `export const PACK_SOURCES: PackSource[] = ${JSON.stringify(packs, null, 1)};`,
    "",
  ].join("\n");
}

/** Writes the file only when it changed (so watchers don't reload for nothing). */
export function writePartsModule(): boolean {
  const next = partsModule();
  if (existsSync(PARTS_TS_PATH) && readFileSync(PARTS_TS_PATH, "utf8") === next) return false;
  writeFileSync(PARTS_TS_PATH, next);
  return true;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const changed = writePartsModule();
  // Check the result with the engine's own loader, so a broken pack fails here with its field.
  void import("../src/packs").then(({ loadPacks }) => {
    const packs = loadPacks(readPacks());
    console.log(`${changed ? "wrote" : "unchanged"} ${PARTS_TS_PATH} (${packs.length} packs: ${packs.map((p) => p.meta.id).join(", ")})`);
  });
}
